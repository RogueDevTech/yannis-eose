export function findBankByName(name: string | null | undefined): NigerianBankOption | null {
  if (!name) return null;
  const trimmed = name.trim().toLowerCase();
  const exact = NIGERIAN_BANKS.find((b) => b.name.toLowerCase() === trimmed);
  if (exact) return exact;
  const aliasCode = BANK_NAME_ALIASES[trimmed];
  if (aliasCode) return NIGERIAN_BANKS.find((b) => b.code === aliasCode) ?? null;
  // Soft contains match when unique
  const hits = NIGERIAN_BANKS.filter(
    (b) => b.name.toLowerCase().includes(trimmed) || trimmed.includes(b.name.toLowerCase()),
  );
  return hits.length === 1 ? (hits[0] ?? null) : null;
}

/** Match NIP code, or map legacy CBN/Paystack codes to NIP. */
export function findBankByCode(code: string | null | undefined): NigerianBankOption | null {
  if (!code) return null;
  const normalized = normalizeCode(code);
  return NIGERIAN_BANKS.find((b) => b.code === normalized) ?? null;
}

/** Resolve bank from either stored code or name (code preferred). */
export function resolveNigerianBank(opts: {
  name?: string | null;
  code?: string | null;
}): NigerianBankOption | null {
  return findBankByCode(opts.code) ?? findBankByName(opts.name);
}
